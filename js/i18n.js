export function lang() {
  const l = state.settings.lang;
  if (l === 'ar' || l === 'en') return l;
  return (navigator.language || 'en').toLowerCase().startsWith('ar') ? 'ar' : 'en';
}
export const isAr = () => lang() === 'ar';

export function num(n) {
  return isAr() ? Number(n).toLocaleString('ar-EG') : Number(n).toLocaleString('en-US');
}

export function t(key, vars) {
  const L = lang();
  let s = S[L][key] ?? S.en[key];
  if (s === undefined) { console.warn('missing i18n', key); return key; }
  if (Array.isArray(s)) s = s[(Math.random() * s.length) | 0];
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (typeof vars[k] === 'number' ? num(vars[k]) : vars[k] ?? ''));
  return s;
}

/** Pick the {ar, en} field for the current UI language. */
export const L = obj => obj[lang()] ?? obj.en;

export function applyLang() {
  const l = lang();
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
  document.title = l === 'ar' ? 'الأربعون — احفظ وراجع' : 'Arbaʿīn — memorise & revise';
}
