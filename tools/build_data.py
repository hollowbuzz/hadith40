#!/usr/bin/env python3
"""Build js/data.js from data/shamela-raw.json (verbatim Arabic) + tools/meta.json
(titles, narrators, takhreej keys, English translations, corrections).

Each paragraph is split into typed segments:
  i = narration frame (narrator, "he said", ...)
  m = matn (the quoted text inside « »)
  q = Qur'an quotation inside the matn ({ })
  t = takhreej / editor's remarks (رواه ...، حديث حسن ...، وفي رواية ...)
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, 'data', 'shamela-raw.json')
META = os.path.join(ROOT, 'tools', 'meta.json')
OUT = os.path.join(ROOT, 'js', 'data.js')

DIAC = re.compile(r'[ً-ْٰـ]')
PARA_TAKH = ('وخرجه', 'وكلهم', 'وله طرق', 'ورواه', 'ومعنى', 'وفي رواية')
TAKH_KW = ('رواه', 'حديث', 'خرجه', 'رويناه')
DROP = {'* * *', 'تم بحمد الله'}


def strip(s):
    return DIAC.sub('', s)


def clean_paras(h):
    """Drop separators and re-join paragraphs that a page break split mid-sentence."""
    paras = [p for p in h['paras'] if strip(p['t']).strip() not in DROP]
    out = []  # list of [text, page]
    for idx, p in enumerate(paras):
        page_break = out and paras[idx - 1]['p'] != p['p']
        if page_break and not re.search(r'[.!?؟»:]\s*$', out[-1][0]):
            out[-1][0] = out[-1][0].rstrip() + ' ' + p['t'].lstrip()
            continue
        out.append([p['t'], p['p']])
    return [t for t, _ in out]


def segment(paras):
    result = []
    state, ret, inq = 'i', None, False
    for ptxt in paras:
        segs = []

        def add(kind, ch):
            if segs and segs[-1][0] == kind:
                segs[-1][1] += ch
            else:
                segs.append([kind, ch])

        s0 = strip(ptxt).lstrip()
        riwaya = s0.startswith('وفي رواية')
        if state != 'm':
            state = 't' if s0.startswith(PARA_TAKH) else 'i'
            ret = None
        tdepth = 0
        for i, ch in enumerate(ptxt):
            if state == 'x':
                rest = strip(ptxt[i:]).lstrip()
                state = 't' if rest.startswith(TAKH_KW) else 'i'
            if state == 'i':
                if ch == '«':
                    state = 'm'
                    add('m', ch)
                else:
                    add('i', ch)
            elif state == 'm':
                if inq:
                    add('q', ch)
                    if ch == '}':
                        inq = False
                elif ch == '{':
                    inq = True
                    add('q', ch)
                elif ch == '»':
                    add('m', ch)
                    state, ret = (ret or 'x'), None
                else:
                    add('m', ch)
            elif state == 't':
                if ch == '«':
                    before = strip(ptxt[:i]).rstrip()
                    if tdepth == 0 and (riwaya or re.search(r'(?:^|\s)قال:$', before) or before.endswith('ولفظه:')):
                        state, ret = 'm', 't'
                        add('m', ch)
                    else:
                        tdepth += 1
                        add('t', ch)
                elif ch == '»' and tdepth > 0:
                    tdepth -= 1
                    add('t', ch)
                else:
                    add('t', ch)
        result.append(segs)
    return result


def main():
    raw = json.load(open(RAW, encoding='utf-8'))
    meta = json.load(open(META, encoding='utf-8'))
    out = []
    for h in raw:
        n = h['n']
        m = meta['hadith'][str(n)]
        paras = clean_paras(h)
        notes = []
        for c in meta.get('corrections', {}).get(str(n), []):
            joined = '\n'.join(paras)
            assert joined.count(c['find']) == 1, (n, c['find'])
            paras = joined.replace(c['find'], c['replace']).split('\n')
            notes.append(c['note'])
        if len(m['en']) != len(paras):
            raise SystemExit(f'hadith {n}: {len(paras)} Arabic paragraphs vs {len(m["en"])} English')
        segs = segment(paras)
        # sanity: every hadith has some matn
        assert any(k == 'm' for p in segs for k, _ in p), n
        out.append({
            'n': n,
            'heading': h['heading'],
            'ibnRajab': n > 42,
            'title': m['title'],
            'narrator': m['narrator'],
            'takhreej': m['takhreej'],
            'paras': segs,
            'en': m['en'],
            'pages': [{'id': pid, 'num': num} for pid, num in zip(h['pages'], h['page_nums'])],
            'notes': notes,
        })
    lines = [
        '// Generated by tools/build_data.py — do not edit by hand.',
        '// Arabic text: «متون طالب العلم - المستوى الأول» (عبد المحسن القاسم), Shamela book 570.',
        'export const SOURCE = ' + json.dumps({
            'title': {'ar': 'متون طالب العلم – المستوى الأول', 'en': 'Mutūn Ṭālib al-ʿIlm – Level One'},
            'editor': {'ar': 'عبد المحسن بن محمد القاسم', 'en': 'ʿAbd al-Muḥsin ibn Muḥammad al-Qāsim'},
            'work': {'ar': 'الأربعون النووية مع زيادة ابن رجب', 'en': 'al-Nawawī’s Forty with Ibn Rajab’s Addition'},
            'url': 'https://shamela.ws/book/570/68',
            'pageUrl': 'https://shamela.ws/book/570/',
        }, ensure_ascii=False) + ';',
        'export const TAKHREEJ = ' + json.dumps(meta['takhreejLabels'], ensure_ascii=False) + ';',
        'export const HADITH = [',
    ]
    for h in out:
        lines.append(json.dumps(h, ensure_ascii=False) + ',')
    lines.append('];')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', OUT, len(out), 'hadith')


if __name__ == '__main__':
    main()
